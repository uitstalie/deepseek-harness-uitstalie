/**
 * Automatic completion report for dispatched workspace tasks.
 *
 * The workspace toolset owns the task record and the dispatcher binding, so the
 * executor's `turn/end` is enough to report back: the hook finds the task that
 * targets the ending Session, delivers one bounded report to the task's
 * `dispatcherSessionId`, and records the turn as a receipt that moves the task
 * to `waiting_review` (or `blocked` when the turn did not complete). The
 * dispatcher does not poll and no process watches other sessions.
 *
 * The delivery is a restricted exception to cross-workspace messaging: it is
 * generated by this trusted hook for the recorded binding, never exposed as a
 * tool action, and `workspace_message.send` keeps rejecting arbitrary
 * cross-workspace sends.
 * @module @deepseek-ai/dsh-workspace-tools/report
 */

import type { Context } from '@deepseek-ai/cordis'
import type { TurnEndInput } from '@deepseek-ai/dsh-dafeiyu'
import type { Session } from '@deepseek-ai/dsh-session'
import type { Workspace } from '@deepseek-ai/dsh-workspace'
import { MESSAGE_TEXT_MAX_CHARS, deliverTaskReport } from './messages.ts'
import type { TaskRecord } from './records.ts'
import { listTasks } from './store.ts'
import { recordTurnCompletion } from './tasks.ts'
import type { TurnReportStatus } from './tasks.ts'
import { oneLine } from './tooling.ts'

/** Statuses that still accept an automatic completion report. */
const REPORTABLE_STATUSES = new Set(['pending', 'in_progress'])

/** Last assistant text observed for each Session, maintained from live events. */
export interface AssistantTextTracker {
  /**
   * Read the latest assistant text for one Session.
   * @param session - Session whose turn ended.
   * @returns the latest assistant text, or undefined when none was seen.
   */
  last(session: Session): string | undefined
  /** Remove the session event listener. */
  dispose(): void
}

/**
 * Track the last assistant text of each Session from committed assistant
 * messages.
 *
 * Synchronous historical reads are deprecated, and a projection for one display
 * string would duplicate the message fold. The listener owns no durable state:
 * a WeakMap keyed by the live Session is released with it, and a resumed Session
 * rebuilds the value from the assistant messages of its current turn.
 * @param ctx - plugin context whose fiber owns the listener.
 * @returns the tracker; dispose it when the contribution unloads.
 */
export function createAssistantTextTracker(ctx: Context): AssistantTextTracker {
  const texts = new WeakMap<Session, string>()
  const off = ctx.on('session/event', (session, event) => {
    if (event.type !== 'assistant/message') return
    const text = messageText(event.data.message)
    if (text.length > 0) texts.set(session, text)
  })
  return { last: session => texts.get(session), dispose: off }
}

/**
 * Handle one finished executor turn: deliver the task-bound report and advance
 * the task.
 *
 * Every failure is contained here. dafeiyu marks a capability failed when its
 * turn hook rejects, so a store or controller problem must be logged instead of
 * failing the whole toolset for later turns; a failed delivery still records
 * the task receipt with the delivery outcome in the note.
 * @param ctx - context carrying the store, registry, and Session controller.
 * @param input - the ending agent, Session, turn, event, and registration signal.
 * @param conclusion - last assistant text tracked for the Session, when there was one.
 */
export async function reportTurnEnd(ctx: Context, input: TurnEndInput, conclusion?: string): Promise<void> {
  try {
    const sessionId = String(input.session.id)
    const workspace = ctx.workspaceRegistry.list()
      .find(candidate => candidate.sessionIds.some(id => String(id) === sessionId))
    if (workspace === undefined) return
    const tasks = (await listTasks(ctx, workspace.id, input.signal))
      .filter(candidate => candidate.targetSessionId === sessionId && REPORTABLE_STATUSES.has(candidate.status))
    if (tasks.length === 0) return
    const completed = input.event.data.reason.kind === 'completed'
    const status: TurnReportStatus = completed ? 'waiting_review' : 'blocked'
    for (const task of tasks) {
      if (task.dispatcherSessionId === undefined || task.dispatcherSessionId === sessionId) continue
      const requestId = `task-report-${task.taskId}-turn-${String(input.turn)}`
      const text = reportText(workspace, task, sessionId, status, conclusion)
      let deliveryNote = 'report not recorded'
      try {
        const sent = await deliverTaskReport(ctx, workspace, {
          sourceSessionId: sessionId,
          targetSessionId: task.dispatcherSessionId,
          taskId: task.taskId,
          text,
          requestId,
        }, input.signal)
        deliveryNote = sent.status === 'delivered'
          ? `report delivered as ${sent.messageId}`
          : sent.status === 'failed'
            ? `report delivery failed: ${sent.error ?? 'declined'}`
            : `report ${sent.status} as ${sent.messageId}`
      } catch (error: unknown) {
        deliveryNote = `report delivery failed: ${String(error)}`
      }
      await recordTurnCompletion(ctx, {
        workspaceId: String(workspace.id),
        taskId: task.taskId,
        status,
        note: oneLine(`turn ${String(input.turn)} ended ${input.event.data.reason.kind}; ${deliveryNote}`, 240),
        requestId,
      }, input.signal, input.session)
    }
  } catch (error: unknown) {
    ctx.logger.warn('workspace-tools: automatic task report failed: %s', String(error))
  }
}

/**
 * Build the bounded dispatcher-facing report.
 * @param workspace - workspace that owns the task.
 * @param task - task whose executor turn ended.
 * @param sessionId - executor Session id.
 * @param status - task state the turn produced.
 * @param conclusion - last assistant text of the turn, when there was one.
 * @returns the message body, at most {@link MESSAGE_TEXT_MAX_CHARS} characters.
 */
function reportText(
  workspace: Workspace,
  task: TaskRecord,
  sessionId: string,
  status: TurnReportStatus,
  conclusion: string | undefined,
): string {
  const header = `[task-report] task ${task.taskId} · workspace ${String(workspace.id)} · session ${sessionId} · ${status}`
  const outcome = conclusion === undefined
    ? 'Conclusion: the turn ended without assistant text.'
    : `Conclusion: ${oneLine(conclusion, 200)}`
  const evidence = `Evidence: task ${task.taskId}, session ${sessionId} in workspace ${String(workspace.id)}; details in workspace_tasks.get and workspace_sessions.get.`
  const text = `${header}\n${outcome}\n${evidence}`
  return text.length <= MESSAGE_TEXT_MAX_CHARS ? text : text.slice(0, MESSAGE_TEXT_MAX_CHARS)
}

/**
 * Extract the text blocks of one assistant message.
 * @param message - committed assistant message.
 * @returns its text joined by newlines, trimmed; an empty string when it has none.
 */
function messageText(message: { readonly content: readonly { readonly type: string }[] }): string {
  return message.content
    .map(block => block.type === 'text' && 'text' in block ? String(block.text) : '')
    .join('\n')
    .trim()
}
